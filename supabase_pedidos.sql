-- ═══════════════════════════════════════════════════════════════════════════
-- PEDIDOS (trabajos a pedido): del presupuesto a la entrega, con código de seguimiento.
--
--   · Cada pedido tiene un CÓDIGO de seguimiento (CC-XXXX-XXXX) y un PIN (por defecto, los últimos 3 números
--     del celular del cliente). Con código + PIN el cliente va a poder ver su pedido en el sitio de seguimiento.
--   · Estados:  presupuestado → aceptado → en_produccion → listo → entregado   (salidas: rechazado, cancelado)
--     "Aceptado" es el momento en que entra la SEÑA: al registrarla, el pedido pasa solo a aceptado
--     y el PRECIO SE CONGELA. Hasta entonces el precio sigue los costos actuales de materiales y tarifas.
--   · Seña, saldo, imágenes de referencia (las que manda el cliente) e imágenes del resultado (cómo quedaría).
--   · pedido_eventos: la línea de tiempo (creado, seña, cambios de estado, cambios de precio...). Es lo que
--     después va a ver el cliente en el sitio de seguimiento (visible_cliente).
--
-- Separado por negocio (org_id), igual que ventas y clientes. Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists public.pedidos (
  id                  uuid primary key default gen_random_uuid(),
  org_id              uuid not null default public.get_org_id(),
  numero              bigint generated by default as identity,
  codigo              text not null unique,                      -- se genera solo: CC-XXXX-XXXX
  pin                 text,                                      -- por defecto: últimos 3 números del celular
  estado              text not null default 'presupuestado'
                        check (estado in ('presupuestado','aceptado','en_produccion','listo','entregado','rechazado','cancelado')),

  cliente_id          uuid references public.clientes(id) on delete set null,
  cliente_nombre      text not null,
  cliente_telefono    text,
  cliente_email       text,

  titulo              text not null,                             -- de qué se trata el pedido
  descripcion         text,

  presupuesto_id      uuid references public.presupuestos(id) on delete set null,
  lista_id            uuid references public.listas_precios(id) on delete set null,
  items               jsonb not null default '[]'::jsonb,        -- los renglones del presupuesto (con piezas y tarifas, para recalcular)

  total               numeric not null default 0,                -- precio vigente
  precio_congelado    boolean not null default false,
  precio_congelado_en timestamptz,

  sena_monto          numeric not null default 0,
  sena_fecha          timestamptz,
  sena_forma_pago     text,
  saldo               numeric generated always as (greatest(total - sena_monto, 0)) stored,

  imagenes_referencia text[] not null default '{}',              -- las que manda el cliente
  imagenes_resultado  text[] not null default '{}',              -- cómo quedaría el producto (las ponemos nosotros)
  nota_cliente        text,                                      -- visible para el cliente en el seguimiento
  nota_interna        text,                                      -- solo para el equipo
  entrega_estimada    date,

  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index if not exists pedidos_org_estado_idx on public.pedidos (org_id, estado, created_at desc);
create index if not exists pedidos_cliente_idx on public.pedidos (cliente_id);

create table if not exists public.pedido_eventos (
  id               bigint generated always as identity primary key,
  pedido_id        uuid not null references public.pedidos(id) on delete cascade,
  org_id           uuid not null,
  fecha            timestamptz not null default now(),
  tipo             text not null,                                -- creado | estado | sena | precio | imagen | nota
  detalle          text,
  visible_cliente  boolean not null default true,
  usuario          uuid default auth.uid()
);
create index if not exists pedido_eventos_pedido_idx on public.pedido_eventos (pedido_id, fecha);

-- ── Reglas automáticas ──────────────────────────────────────────────────────

-- "$ 1.234.567" (pesos enteros, con punto de miles), siempre igual sin depender del idioma del servidor.
create or replace function public.pesos(n numeric) returns text
language sql immutable as $$
  select '$ ' || regexp_replace(to_char(round(coalesce(n, 0)), 'FM9999999999990'), '(\d)(?=(\d{3})+$)', '\1.', 'g')
$$;

-- Antes de guardar: código, PIN, "aceptado" y congelar al entrar la seña, y no tocar el precio congelado.
create or replace function public.pedidos_antes() returns trigger
language plpgsql as $$
declare c text; digitos text;
begin
  if tg_op = 'INSERT' and (new.codigo is null or new.codigo = '') then
    loop
      c := 'CC-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 4))
                 || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 4));
      exit when not exists (select 1 from public.pedidos where codigo = c);
    end loop;
    new.codigo := c;
  end if;

  -- PIN = últimos 3 números del celular (si no se puso uno a mano)
  if new.pin is null or new.pin = '' then
    digitos := regexp_replace(coalesce(new.cliente_telefono, ''), '\D', '', 'g');
    if length(digitos) >= 3 then new.pin := right(digitos, 3); end if;
  end if;

  -- Entra la seña por primera vez (al crear o al editar): el pedido queda aceptado y el precio se congela.
  if new.sena_monto > 0 and (tg_op = 'INSERT' or coalesce(old.sena_monto, 0) = 0) then
    if new.sena_fecha is null then new.sena_fecha := now(); end if;
    if new.estado = 'presupuestado' then new.estado := 'aceptado'; end if;
    if not new.precio_congelado then new.precio_congelado := true; new.precio_congelado_en := now(); end if;
  end if;

  if tg_op = 'UPDATE' then
    new.updated_at := now();
    if new.precio_congelado and not old.precio_congelado and new.precio_congelado_en is null then
      new.precio_congelado_en := now();
    end if;
    -- Con el precio congelado, el total no se puede cambiar (hay que "descongelar" primero, a propósito).
    if old.precio_congelado and new.precio_congelado and new.total <> old.total then
      raise exception 'El precio de este pedido está congelado (ya tiene seña). Descongelalo primero si querés cambiarlo.';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists pedidos_antes on public.pedidos;
create trigger pedidos_antes before insert or update on public.pedidos
  for each row execute function public.pedidos_antes();

-- Después de guardar: la línea de tiempo.
create or replace function public.pedidos_despues() returns trigger
language plpgsql security definer set search_path = public as $$
declare etiqueta text;
begin
  if tg_op = 'INSERT' then
    insert into pedido_eventos (pedido_id, org_id, tipo, detalle) values (new.id, new.org_id, 'creado', 'Pedido creado');
    return new;
  end if;

  if new.estado is distinct from old.estado then
    etiqueta := case new.estado
      when 'presupuestado' then 'Presupuestado' when 'aceptado' then 'Aceptado' when 'en_produccion' then 'En producción'
      when 'listo' then 'Listo para entregar' when 'entregado' then 'Entregado' when 'rechazado' then 'Rechazado'
      when 'cancelado' then 'Cancelado' else new.estado end;
    insert into pedido_eventos (pedido_id, org_id, tipo, detalle) values (new.id, new.org_id, 'estado', etiqueta);
  end if;
  if new.sena_monto is distinct from old.sena_monto and new.sena_monto > 0 then
    insert into pedido_eventos (pedido_id, org_id, tipo, detalle)
      values (new.id, new.org_id, 'sena', 'Seña registrada: ' || public.pesos(new.sena_monto));
  end if;
  if new.total is distinct from old.total then
    insert into pedido_eventos (pedido_id, org_id, tipo, detalle)
      values (new.id, new.org_id, 'precio', 'Precio actualizado: de ' || public.pesos(old.total) || ' a ' || public.pesos(new.total));
  end if;
  if new.precio_congelado is distinct from old.precio_congelado then
    insert into pedido_eventos (pedido_id, org_id, tipo, detalle, visible_cliente)
      values (new.id, new.org_id, 'precio', case when new.precio_congelado then 'Precio confirmado' else 'Precio descongelado' end, new.precio_congelado);
  end if;
  if coalesce(array_length(new.imagenes_resultado, 1), 0) > coalesce(array_length(old.imagenes_resultado, 1), 0) then
    insert into pedido_eventos (pedido_id, org_id, tipo, detalle) values (new.id, new.org_id, 'imagen', 'Nueva imagen de cómo quedaría');
  end if;
  return new;
end $$;
drop trigger if exists pedidos_despues on public.pedidos;
create trigger pedidos_despues after insert or update on public.pedidos
  for each row execute function public.pedidos_despues();

-- ── Permisos: cada negocio ve y toca solo lo suyo ───────────────────────────
alter table public.pedidos enable row level security;
alter table public.pedido_eventos enable row level security;
drop policy if exists pedidos_org on public.pedidos;
drop policy if exists pedido_eventos_org on public.pedido_eventos;
create policy pedidos_org on public.pedidos for all using (org_id = public.get_org_id()) with check (org_id = public.get_org_id());
create policy pedido_eventos_org on public.pedido_eventos for all using (org_id = public.get_org_id()) with check (org_id = public.get_org_id());

-- Nada de escritura para el rol anónimo (el sitio de seguimiento va a pasar por una función del servidor).
revoke insert, update, delete, truncate, references, trigger on public.pedidos, public.pedido_eventos from anon;
